/**
 * Compiles the icon and illustration sources into the panel data modules and the finder sprite.
 *   pnpm icons:build
 * Inputs:  src/assets/icons/*.svg (24-unit line icons, `<name>-fill.svg` = filled variant),
 *          src/assets/empty/*.svg (64-unit empty-state art), src/assets/item-art/*.svg (item illustrations).
 * Outputs: src/app/ui/icons.generated.ts, src/app/ui/item-art.generated.ts, public/p/icons.svg.
 * test/icons.test.ts fails when the outputs are stale, so run this after editing any source.
 */
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import {
  type ArtNode,
  buildSprite,
  compileArt,
  compileLineIcon,
  type IconPaths,
  TONE_OPACITY,
} from "../vite/icons.ts";

const root = path.resolve(import.meta.dirname, "..");
const svgFiles = (dir: string) =>
  readdirSync(path.join(root, dir))
    .filter((f) => f.endsWith(".svg"))
    .sort()
    .map((f) => ({ name: f.slice(0, -4), source: readFileSync(path.join(root, dir, f), "utf8") }));

function compileOrThrow<T>(file: string, fn: () => T): T {
  try {
    return fn();
  } catch (error) {
    throw new Error(`${file}: ${error instanceof Error ? error.message : String(error)}`);
  }
}

const icons: Record<string, IconPaths> = {};
const fills: Record<string, IconPaths> = {};
for (const { name, source } of svgFiles("src/assets/icons")) {
  const { paths } = compileOrThrow(`src/assets/icons/${name}.svg`, () => compileLineIcon(source, 24));
  if (name.endsWith("-fill")) fills[name.slice(0, -5)] = paths;
  else icons[name] = paths;
}
for (const base of Object.keys(fills)) {
  if (!icons[base]) throw new Error(`src/assets/icons/${base}-fill.svg has no outline ${base}.svg`);
}
const empty: Record<string, { paths: IconPaths; tone: string }> = {};
for (const { name, source } of svgFiles("src/assets/empty")) {
  empty[name] = compileOrThrow(`src/assets/empty/${name}.svg`, () => compileLineIcon(source, 64));
}
const art: Record<string, ArtNode[]> = {};
for (const { name, source } of svgFiles("src/assets/item-art")) {
  art[name] = compileOrThrow(`src/assets/item-art/${name}.svg`, () => compileArt(source).nodes);
}

const union = (names: string[]) => names.map((n) => JSON.stringify(n)).join(" | ");
const HEADER = "// Generated by `pnpm icons:build` (scripts/build-icons.ts) from src/assets. Do not edit.\n";

const iconsTs = `${HEADER}
/** [stroke, fill, fill + stroke (evenodd)] path data on the 24-unit grid; "" = none. */
export type IconPaths = readonly [stroke: string, fill?: string, fillStroke?: string];
export type IconName = ${union(Object.keys(icons))};
export type FilledIconName = ${union(Object.keys(fills))};
export type EmptyArtName = ${union(Object.keys(empty))};

export const ICONS: Record<IconName, IconPaths> = ${JSON.stringify(icons)};

/** Solid variants (selected tab, iOS style). Same silhouette as the outline. */
export const ICON_FILLS: Record<FilledIconName, IconPaths> = ${JSON.stringify(fills)};

/** Opacity of the tonal (secondary) fill in empty-state art. */
export const EMPTY_TONE_OPACITY = ${TONE_OPACITY};

/** 64-unit empty-state art; \`tone\` is painted with currentColor at EMPTY_TONE_OPACITY. */
export const EMPTY_ART: Record<EmptyArtName, { paths: IconPaths; tone: string }> = ${JSON.stringify(empty)};
`;

const artTs = `${HEADER}
/** [tag, React props, children]. Ids are local; ItemArt prefixes them per instance. */
export type ArtNode = [string, Record<string, string>, ArtNode[]];
export type ItemArtName = ${union(Object.keys(art))};

export const ITEM_ART: Record<ItemArtName, ArtNode[]> = ${JSON.stringify(art)};
`;

const outputs = {
  "src/app/ui/icons.generated.ts": iconsTs,
  "src/app/ui/item-art.generated.ts": artTs,
  "public/p/icons.svg": buildSprite(icons, empty),
};
for (const [file, content] of Object.entries(outputs)) writeFileSync(path.join(root, file), content);
execFileSync(
  path.join(root, "node_modules/.bin/biome"),
  ["format", "--write", "src/app/ui/icons.generated.ts", "src/app/ui/item-art.generated.ts"],
  { cwd: root, stdio: "inherit" },
);
console.log(
  `icons: ${Object.keys(icons).length} line (${Object.keys(fills).length} filled), ` +
    `${Object.keys(empty).length} empty-state, ${Object.keys(art).length} item illustrations`,
);
